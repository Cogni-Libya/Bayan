"""Write results.tex from the model-1 test run, so no reported number is typed by hand.

Inputs (one directory, produced by the run described in the report, sec. 3.3):
    score_<run>.txt     output of scripts/evaluation/score.py
    analyse_<run>.json  behaviour statistics (copy rate, edit size, words kept)
for runs samer_test_greedy, samer_test_beam4, barec_stripped_greedy,
barec_raw_greedy, daasi_greedy, plus analyse_samer_test_human.json (the human reference
scored as if it were a model).

    python make_results.py <results-dir>
"""
import json
import re
import sys
from pathlib import Path

D = Path(sys.argv[1])
OUT = Path(__file__).resolve().parent / "results.tex"


def score(run):
    """{section: {bucket: {metric: value}}} from score.py's printout."""
    out, section, bucket = {}, None, None
    for line in (D / f"score_{run}.txt").read_text().splitlines():
        if m := re.match(r"=+ (.+?) =+", line):
            section = out.setdefault(m.group(1), {})
        elif m := re.match(r"--- (.+?) \(n=(\d+)\) ---", line):
            bucket = section.setdefault(m.group(1), {"n": int(m.group(2))})
        elif m := re.match(r"(Copy rate|SARI|BLEU|BERTScore|Readability drop):\s+(\S+)", line):
            bucket[m.group(1)] = float(m.group(2))
    return out


def analyse(run):
    return json.loads((D / f"analyse_{run}.json").read_text())


g, b = score("samer_test_greedy"), score("samer_test_beam4")
rs, rr = score("barec_stripped_greedy"), score("barec_raw_greedy")
ag, ab = analyse("samer_test_greedy"), analyse("samer_test_beam4")
ars, arr = analyse("barec_stripped_greedy"), analyse("barec_raw_greedy")
ah = analyse("samer_test_human")
da, ada = score("daasi_greedy"), analyse("daasi_greedy")
sub = analyse("barec_diacritized_subset")

M, C = "MODEL", "COPY BASELINE"
ALL, CH, UN, NR = "Overall", "Changed references", "Unchanged references", "No references"
f2 = lambda x: f"{x:.2f}".replace("-", "\u2212")
signed = lambda x: f"{x:+.2f}".replace("-", "\u2212")
f1 = lambda x: f"{x:.1f}"
pct = lambda x: f"{100 * x:.1f}\\%"


def row(name, s, bold=()):
    cells = [s[ALL]["SARI"], s[CH]["SARI"], s[UN]["SARI"], s[ALL]["BLEU"],
             s[ALL]["BERTScore"], s[ALL]["Readability drop"]]
    txt = [f2(v) for v in cells] + [pct(s[ALL]["Copy rate"])]
    txt = [f"\\textbf{{{t}}}" if i in bold else t for i, t in enumerate(txt)]
    return f"{name} & " + " & ".join(txt) + r" \\ \hline"


gain = lambda s: s[M][CH]["SARI"] - s[C][CH]["SARI"]
macros = {
    "copytestall": f2(g[C][ALL]["SARI"]),
    "copytestchanged": f2(g[C][CH]["SARI"]),
    "testchangedn": f"{g[M][CH]['n']:,}",
    "testunchangedn": f"{g[M][UN]['n']:,}",
    "greedyall": f2(g[M][ALL]["SARI"]), "greedychanged": f2(g[M][CH]["SARI"]),
    "greedyunchanged": f2(g[M][UN]["SARI"]),
    "beamall": f2(b[M][ALL]["SARI"]), "beamchanged": f2(b[M][CH]["SARI"]),
    "beamunchanged": f2(b[M][UN]["SARI"]),
    "greedygain": signed(gain(g)), "beamgain": signed(gain(b)),
    "greedyallgap": signed(g[M][ALL]['SARI'] - g[C][ALL]['SARI']),
    "greedycopy": f1(ag["copy_rate_pct"]), "humancopy": f1(ah["copy_rate_pct"]),
    "greedyuntouched": f1(ag["untouched_on_changed_pct"]),
    "greedyoveredit": f1(ag["changed_on_unchanged_pct"]),
    "beamoveredit": f1(ab["changed_on_unchanged_pct"]),
    "greedysingle": f1(ag["single_word_edit_pct"]), "humansingle": f1(ah["single_word_edit_pct"]),
    "greedyratio": f"{ag['median_len_ratio']:.2f}",
    "strippedkept": f1(ars["source_words_kept_pct"]), "rawkept": f1(arr["source_words_kept_pct"]),
    "strippedlost": f1(ars["rows_losing_half_pct"]), "rawlost": f1(arr["rows_losing_half_pct"]),
    "strippedbert": f2(rs[M][NR]["BERTScore"]), "rawbert": f2(rr[M][NR]["BERTScore"]),
    "strippeddrop": f2(rs[M][NR]["Readability drop"]), "rawdrop": f2(rr[M][NR]["Readability drop"]),
    "strippedcopy": pct(rs[M][NR]["Copy rate"]), "rawcopy": pct(rr[M][NR]["Copy rate"]),
    "daasisari": f2(da[M][ALL]["SARI"]), "daasicopysari": f2(da[C][ALL]["SARI"]),
    "daasigain": signed(da[M][ALL]['SARI'] - da[C][ALL]['SARI']),
    "daasibert": f2(da[M][ALL]["BERTScore"]), "daasidrop": f2(da[M][ALL]["Readability drop"]),
    "daasicopy": pct(da[M][ALL]["Copy rate"]), "daasikept": f1(ada["source_words_kept_pct"]),
    "diacn": f"{sub['n']:,}",
    "diacrawkept": f1(sub["raw"]["kept_pct"]), "diacrawlost": f1(sub["raw"]["losing_half_pct"]),
    "diacstrippedkept": f1(sub["stripped"]["kept_pct"]), "diacstrippedlost": f1(sub["stripped"]["losing_half_pct"]),
}

